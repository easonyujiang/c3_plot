// Payload values below are model-derived UI fixtures, never flight measurements.
const {chromium}=require('playwright');
const assert=require('assert/strict'),fs=require('fs'),path=require('path');
const crypto=require('crypto');
const root=path.resolve(__dirname,'..');
function originalFiles(){
 return Object.fromEntries(fs.readdirSync(path.join(root,'rockets')).sort().map(name=>[name,crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'rockets',name))).digest('hex')]));
}
const out=path.join(__dirname,'../output/automatic_import_20261011/full-browser');
fs.mkdirSync(out,{recursive:true});
(async()=>{
 const before=originalFiles();
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const errors=[];let savedSlug;
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8878/workspace/#/tools/import');
  await page.getByPlaceholder('搜索火箭或存档').fill('C3MassValidation20261010');
  await page.getByRole('button',{name:/C3MassValidation20261010 · Neutrons I 2630.craft · 点击导入/}).click();
  await page.getByText('已与游戏编辑器结算质量、当前 Mod 和火箭版本核对。分级与发动机数据自动填写。').waitFor({timeout:60000});
  assert.equal(await page.locator('input[type=number]:not([readonly])').count(),3);
  const readonly=await page.locator('input[readonly]').evaluateAll(inputs=>inputs.map(i=>Number(i.value)));
  assert.equal(readonly.length,4);assert(Math.abs(readonly[0]-131.992614)<.000001);
  const fixtures=[4.898,1.609,1.015];
  const testName='Neutron 验收 '+Date.now();
  await page.getByLabel('火箭名称').fill(testName);
  for(let i=0;i<3;i++)await page.getByLabel('实测运力 / t',{exact:true}).nth(i).fill(String(fixtures[i]));
  await page.screenshot({path:path.join(out,'automatic-import-three-inputs.png'),fullPage:true});
  const saveResponse=page.waitForResponse(r=>r.url().endsWith('/api/rockets')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'保存并绘制曲线'}).click();
  const saved=await saveResponse;assert(saved.ok(),await saved.text());savedSlug=(await saved.json()).slug;
  await page.getByRole('img',{name:'C3 与可用载荷曲线'}).waitFor();
  await page.reload();
  await page.getByText('可用容积 126,420 L',{exact:true}).waitFor();
  await page.getByText('总推力 2400.0 kN',{exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'saved-dictionary.png'),fullPage:true});
  const cfg=await (await page.request.get(`http://127.0.0.1:8878/api/rockets/${savedSlug}`)).json();
  assert.equal(cfg.automatic_identification.status,'verified_editor_snapshot');
  assert.equal(cfg.stages[0].runtime_performance.thrust,2400);
  assert.equal(cfg.stages[1].runtime_performance.thrust,213);
  assert.equal(cfg.stages[0].tank_states[0].fields.totalVolume,'147000');
  assert.equal(cfg.calibration[0].benchmark,'220 km 圆轨道');
  await page.getByRole('navigation',{name:'主导航'}).getByRole('link',{name:'工具箱',exact:true}).click();
  const query=page.waitForResponse(r=>r.url().endsWith('/api/mission-query'));
  await page.getByRole('button',{name:'筛选火箭'}).click();
  const mission=await (await query).json();
  const candidate=mission.results.find(r=>r.slug===savedSlug);
  assert(candidate&&candidate.verified_feasible===true);
  assert(candidate.verified_capacity>.7);
  assert.equal(mission.mission.periapsis_km,400);assert.equal(mission.mission.apoapsis_km,40000);assert.equal(mission.mission.inclination_deg,89);
  assert.equal(mission.mission.post_parking_ignitions,2);
  await page.locator('.candidate').filter({hasText:testName}).waitFor();
  await page.screenshot({path:path.join(out,'acceptance-700kg.png'),fullPage:true});
  await page.getByLabel('扣减整流罩',{exact:true}).check();
  await page.getByLabel('整流罩质量 / t',{exact:true}).fill('0.2');
  await page.getByText('整流罩扣减已变化，请重新筛选。',{exact:true}).waitFor();
  const fairingQuery=page.waitForResponse(r=>r.url().endsWith('/api/mission-query'));
  await page.getByRole('button',{name:'筛选火箭'}).click();
  const fairingResponse=await fairingQuery;
  assert(Math.abs(fairingResponse.request().postDataJSON().payload_t-.9)<1e-10);
  const fairingMission=await fairingResponse.json();
  const withFairing=fairingMission.results.find(r=>r.slug===savedSlug);
  assert(withFairing.verified_feasible);
  assert(Math.abs(withFairing.verified_capacity-candidate.verified_capacity)<.002);
  const fairingText=await page.locator('.candidate').filter({hasText:testName}).innerText();
  assert(fairingText.includes('998 kg')&&fairingText.includes('298 kg'));
  await page.goto(`http://127.0.0.1:8878/workspace/#/dictionary/${encodeURIComponent(savedSlug)}`);
  const curve=page.getByRole('img',{name:'C3 与可用载荷曲线'});
  await curve.waitFor();
  // Full navigation resets display state; explicitly enable the allowance.
  await page.getByLabel('扣减整流罩',{exact:true}).check();
  await page.waitForFunction(()=>document.querySelector('.capacity-plot')?.data?.some(t=>t.customdata?.some((v,i)=>v!==null&&Math.abs(v-t.y[i]-.2)<1e-8)));
  const deducted=await curve.evaluate(el=>JSON.stringify(el.data.map(t=>t.y)));
  await page.getByLabel('扣减整流罩',{exact:true}).uncheck();
  await page.waitForFunction(()=>document.querySelector('.capacity-plot')?.data?.every(t=>t.customdata.every((v,i)=>v===null||Math.abs(v-t.y[i])<1e-8)));
  const gross=await curve.evaluate(el=>JSON.stringify(el.data.map(t=>t.y)));
  assert.notEqual(deducted,gross,'Fairing must shift the displayed curve');
  assert.deepEqual(originalFiles(),before,'Validation must not write formal rocket files');
  fs.writeFileSync(path.join(out,'acceptance.json'),JSON.stringify({fixture_provenance:'model-derived capacities for UI testing only; not new flight measurements',formalRocketFilesUnchanged:true,formalRocketHashes:before,fairing:{mass_t:.2,netPayloadKg:998,marginKg:298,curveChanged:true},fixtures,savedSlug,readonly,candidate,mission:mission.mission,errors},null,2));
  assert.deepEqual(errors,[]);console.log(JSON.stringify({savedSlug,capacity:candidate.verified_capacity,automaticImport:true,persisted:true,onlyThreeCapacityInputs:true,errors}));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
